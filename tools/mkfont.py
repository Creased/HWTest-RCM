# 0xC0 up, where LVGL's own symbols live when built without UTF-8: below it,
# 0x80-0xBF, a leading byte is a button-matrix control code (tab names,
# message box buttons) and is never drawn as a letter.
ICON_FIRST = 0xC0


def _open(path: str, weight: int, px: int) -> freetype.Face:
    """A variable face at `weight`, and at the optical size for `px` when the
    face has one (Inter's opsz axis); other axes stay at their defaults."""
    face = freetype.Face(path)
    axes = face.get_variation_info().axes
    coords = []
    for a in axes:
        v = a.default
        if a.tag == "wght":
            v = float(weight)
        elif a.tag == "opsz":
            v = min(max(float(px), a.minimum), a.maximum)
        coords.append(v)
    face.set_var_design_coords(tuple(coords))
    return face


class Blob:
    def __init__(self) -> None:
        self.data = bytearray()

    def add(self, rows: list[list[int]], w: int) -> int:
        """Pack a glyph (rows of 0..255 coverage) at BPP, MSB first."""
        off = len(self.data)
        levels = (1 << BPP) - 1
        for row in rows:
            acc, nbits = 0, 0
            for x in range(w):
                v = (row[x] * levels + 127) // 255
                acc = (acc << BPP) | v
                nbits += BPP
                if nbits == 8:
                    self.data.append(acc)
                    acc, nbits = 0, 0
            if nbits:
                self.data.append(acc << (8 - nbits))
        return off


def _render(face: freetype.Face, cp: int, h: int, top: int,
            min_w: int = 0, center: bool = False) -> tuple[int, list[list[int]]]:
    """One glyph in an h-row cell; `top` is the baseline's row."""
    face.load_char(cp, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
    g = face.glyph
    bm = g.bitmap
    adv = int(round(g.advance.x / 64.0))
    w = max(adv, min_w, 1)
    ox = g.bitmap_left
    if center:
        w = max(w, bm.width + 2)
        ox = (w - bm.width) // 2
    oy = top - g.bitmap_top
    rows = [[0] * w for _ in range(h)]
    buf = bm.buffer          # a fresh copy on every access: read it once
    for y in range(bm.rows):
        ty = oy + y
        if not 0 <= ty < h:
            continue
        for x in range(bm.width):
            tx = ox + x
            if 0 <= tx < w:
                rows[ty][tx] = max(rows[ty][tx], buf[y * bm.pitch + x])
    return w, rows


def _metrics(face: freetype.Face, px: int) -> tuple[int, int, int]:
    face.set_pixel_sizes(0, px)
    asc = math.ceil(face.size.ascender / 64.0)
    desc = math.ceil(-face.size.descender / 64.0)
    face.load_char("H", freetype.FT_LOAD_RENDER)
    cap = face.glyph.bitmap_top
    return asc, asc + desc, cap


def _emit_font(out: list[str], name: str, first: int, glyphs: list[tuple[int, int]],
               h: int, blob_off_base: str = "gui_font_blob") -> None:
    out.append(f"static const lv_font_glyph_dsc_t {name}_dsc[] = {{")
    for w, off in glyphs:
        out.append(f"    {{.w_px = {w}, .glyph_index = {off}}},")
    out.append("};")
    out.append(f"lv_font_t {name} = {{")
    out.append(f"    .unicode_first = {first},")
    out.append(f"    .unicode_last  = {first + len(glyphs) - 1},")
    out.append(f"    .h_px          = {h},")
    out.append(f"    .glyph_bitmap  = {blob_off_base},")
    out.append(f"    .glyph_dsc     = {name}_dsc,")
    out.append(f"    .glyph_cnt     = {len(glyphs)},")
    out.append("    .unicode_list  = NULL,")
    out.append("    .get_bitmap    = lv_font_get_bitmap_continuous,")
    out.append("    .get_width     = lv_font_get_width_continuous,")
    out.append(f"    .bpp           = {BPP},")
    out.append("    .monospace     = 0,")
    out.append("    .next_page     = NULL,")
    out.append("};")
    out.append("")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--text", required=True)
    ap.add_argument("--mono", required=True)
    ap.add_argument("--icons", required=True)
    ap.add_argument("--outdir", default=os.path.join(os.path.dirname(__file__), "..", "gui"))
    args = ap.parse_args()

    paths = {"text": args.text, "mono": args.mono}
    blob = Blob()
    out = [
        "/* Generated by tools/mkfont.py - do not edit. */",
        '#include "gui_fonts.h"',
        "",
        "extern const uint8_t gui_font_blob[];",
        "",
    ]
    text_meta: dict[str, tuple[int, int, int]] = {}

    for name, key, weight, px in TEXT_FONTS:
        face = _open(paths[key], weight, px)
        asc, h, cap = _metrics(face, px)
        text_meta[name] = (asc, h, cap)
        glyphs = []
        for cp in range(0x20, 0x7F):
            w, rows = _render(face, cp, h, asc)
            glyphs.append((w, blob.add(rows, w)))
        # Offsets are relative to the blob start; pin each font to it.
        _emit_font(out, name, 0x20, glyphs, h)

    fa = freetype.Face(args.icons)

    def icon_font(name: str, h: int, icon_px: int, center_row: float) -> None:
        fa.set_pixel_sizes(0, icon_px)
        glyphs = []
        for _, cp in ICONS:
            fa.load_char(cp, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
            g = fa.glyph
            # Centre the glyph's ink on center_row.
            top = int(round(center_row + g.bitmap_top - g.bitmap.rows / 2.0))
            w, rows = _render(fa, cp, h, top, min_w=icon_px, center=True)
            glyphs.append((w, blob.add(rows, w)))
        _emit_font(out, name, ICON_FIRST, glyphs, h)

    for name, parent, scale in ICON_EXT:
        asc, h, cap = text_meta[parent]
        icon_font(name, h, max(8, int(round(cap * scale))), asc - cap / 2.0)
    for name, h in ICON_SOLO:
        icon_font(name, h, int(h * 0.86), h / 2.0)

    os.makedirs(os.path.join(args.outdir, "res"), exist_ok=True)
    with open(os.path.join(args.outdir, "res", "fonts.bin"), "wb") as f:
        f.write(blob.data)
    with open(os.path.join(args.outdir, "gui_fonts.c"), "w", newline="\n") as f:
        f.write("\n".join(out))

    hdr = [
        "/* Generated by tools/mkfont.py - do not edit. */",
        "#ifndef GUI_FONTS_H",
        "#define GUI_FONTS_H",
        "",
        "#include <libs/lvgl/lv_misc/lv_font.h>",
        "",
    ]
    for name, *_ in TEXT_FONTS:
        hdr.append(f"extern lv_font_t {name};")
    for name, *_ in ICON_EXT + ICON_SOLO:
        hdr.append(f"extern lv_font_t {name};")
    hdr.append("")
    hdr.append("/* Icon letters: valid in every gui_icons_* font, and inline in a")
    hdr.append(" * text font once gui_fonts_init() has chained its icon face. */")
    for i, (iname, _) in enumerate(ICONS):
        hdr.append(f'#define ICON_{iname:<10} "\\x{ICON_FIRST + i:02X}"')
    hdr.append("")
    hdr.append("void gui_fonts_init(void);")
    hdr.append("")
    hdr.append("#endif")
    with open(os.path.join(args.outdir, "gui_fonts.h"), "w", newline="\n") as f:
        f.write("\n".join(hdr) + "\n")

    print(f"fonts.bin {len(blob.data)} bytes, {len(TEXT_FONTS)} text + "
          f"{len(ICON_EXT) + len(ICON_SOLO)} icon faces")


if __name__ == "__main__":
    main()
